/*


 领地划界状态标志枚举.
 也就是之前的Spaces之类的"领空"相关的概念.

 自从有这个枚举后,我们的逻辑有一些重要的更新,那就是用这个枚举来确认的多种领空状态.

 来自思维导图的内容:
	 领空状态,领空演化,领空状态循环标记
	   萌芽状态

		   有分界线的意思了.圈地中

		   就像画了一条或多条线,多边形没闭合,不确认形状
			   意思为有修饰符了
			   或者有多个修饰符呢
	   已确认类型状态
		   即待进入(待使用)领空状态

		   分界线闭合了,没进入圈中

		   就像画了多条线的最后一条,多边形闭合,确认了形状
			   使用类型修饰符等方式
			   结束领空的萌芽状态,进入领空定型状态
	   结束领空界限划分动作,切换到迈入凌空状态
		   即进入领空使用中状态

		   就像围成的面被点击,在面上做新的动作中(画线呢?)
	   结束领空使用状态,即跳出领空状态,从这个领空中逃离

		   ESC,取消上个领空的使用,跳出到世界(或者是父领空)当中

	   等待下一个领空的萌芽, 画条线吧?(下一个状态就可能是萌芽了,比如又输入了public,或者可能是已确认类型状态比如直接输入了namespace)

*/

namespace CS2TS.Model;

/// <summary>
///     领地划界状态标志枚举,就是之前的领空相关的概念.
/// </summary>
public enum TerritoryDemarcationStatusFlagEnum
{
	/// <summary>
	///     萌芽状态,有分界线的意思了.圈地中,就像画了一条或多条线,多边形没闭合,不确认形状,意思为有修饰符了,或者有多个修饰符.
	///     比如输入了 public 这种状态,还不能确认后面是不是class/static之类的
	/// </summary>
	Bud = 0,

	/// <summary>
	///     已确认类型状态,即待进入(待使用)领空状态,分界线闭合了,没进入圈中,就像画了多条线的最后一条,多边形闭合,确认了形状,使用类型修饰符等方式,结束领空的萌芽状态,进入领空定型状态
	///     比如输入了 public class 这种状态.类型已经确认了,但是还没有进入领空状态
	/// </summary>
	ConfirmedType = 1,

	/// <summary>
	///     结束领空界限划分动作,切换到迈入凌空状态
	///     即进入领空使用中状态,就像围成的面被点击,在面上做新的动作中(画线呢?),比如输入了 public class A { 这种状态,已经进入了领空状态
	/// </summary>
	IntoUse = 2,

	/// <summary>
	///     结束领空使用状态,即跳出领空状态,从这个领空中逃离
	///     ESC,取消上个领空的使用,跳出到世界(或者是父领空)当中
	///     等待下一个领空的萌芽, 画条线吧?
	///     比如输入了 public class A { } 这种状态,已经跳出了领空状态
	/// </summary>
	Escape = 3
}